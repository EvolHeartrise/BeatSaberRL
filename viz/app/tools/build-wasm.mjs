// Builds the Flux judge (rust/flux-wasm — the env's own geom.rs / flux.rs /
// combo.rs compiled to wasm32) and inlines it as base64 into
// src/lib/fluxcore.gen.js, which fluxcore.js imports. Generated, never
// committed: every `npm run dev|build|test` rebuilds it from the Rust
// source, so the game can only ever run the env's current rules.
//
// Needs cargo + the wasm32-unknown-unknown target
// (`rustup target add wasm32-unknown-unknown`).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const crate = resolve(here, "../../../rust/flux-wasm");
const target = "wasm32-unknown-unknown";

try {
  execFileSync("cargo", ["build", "--release", "--target", target, "--quiet"],
    { cwd: crate, stdio: "inherit" });
} catch (e) {
  console.error(
    "\nbuild-wasm: cargo could not build rust/flux-wasm for " + target + ".\n" +
    "Install the target with `rustup target add " + target + "` and retry.\n");
  process.exit(1);
}

const wasm = readFileSync(
  resolve(crate, "target", target, "release", "flux_wasm.wasm"));
const out = resolve(here, "../src/lib/fluxcore.gen.js");
writeFileSync(out,
  "// GENERATED by tools/build-wasm.mjs from rust/flux-wasm — do not edit.\n" +
  `export default "${wasm.toString("base64")}";\n`);
console.log(`build-wasm: ${wasm.length} B -> src/lib/fluxcore.gen.js`);
