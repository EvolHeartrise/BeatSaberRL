// Compose the raw Unity-space meshes into scene-local parts for the viewer.
// Unity/world (x,y,z) -> scene (x,y,-z); the mirror flips winding, so each
// part's triangle order is checked against its vertex normals and flipped
// where the geometric normal disagrees.
import { readFileSync, writeFileSync } from "node:fs";
const raw = JSON.parse(readFileSync("meshes_raw.json", "utf8"));

const rotZ = (deg) => { const a = deg * Math.PI / 180, c = Math.cos(a), s = Math.sin(a);
  return ([x, y, z]) => [c * x - s * y, s * x + c * y, z]; };
const ident = (v) => v;
// part: source, unity transform (scale, rotate, translate) applied in that order
const parts = {
  note:     { src: "cube" },
  arrow:    { src: "arrow", scale: [2, 2, 2], rot: rotZ(90), pos: [0, 0, -0.238] },
  dot:      { src: "dot", scale: [0.35, 0.35, 1], pos: [0, 0, -0.215] },
  chainHead:{ src: "chainHead" },
  chainLink:{ src: "chainLink" },
  linkDot:  { src: "dot", scale: [0.075, 0.075, 0.5], rot: rotZ(90), pos: [0, 0, -0.235] },
  bomb:     { src: "bomb" },
  blade:    { src: "blade", pos: [0, 0, -0.08] },
  handle:   { src: "handle", pos: [0, 0, -0.08] },
  // headset (Player/Headset.fbx, scene scale 0.35) deliberately not baked
  // since 2026-09-06 — the viewer shows the bare skeleton head
};
const out = {};
let total = 0;
for (const [name, P] of Object.entries(parts)) {
  const m = raw[P.src];
  const sc = P.scale ?? [1, 1, 1], rot = P.rot ?? ident, tr = P.pos ?? [0, 0, 0];
  const nv = m.p.length / 3;
  const pos = new Array(nv * 3), nrm = new Array(nv * 3);
  for (let i = 0; i < nv; i++) {
    // Unity's FBX/OBJ import negates x (right- to left-handed) BEFORE the
    // prefab transform; the scene then mirrors z. Two mirrors = a rotation,
    // so triangle winding is preserved (checked below anyway).
    let v = [-m.p[3 * i] * sc[0], m.p[3 * i + 1] * sc[1], m.p[3 * i + 2] * sc[2]];
    v = rot(v); v = [v[0] + tr[0], v[1] + tr[1], v[2] + tr[2]];
    // normals: rotate only (non-uniform scale is only on the dots' z, whose
    // faces are axis-aligned, so the rotated normal stays correct)
    let n = rot([-m.n[3 * i], m.n[3 * i + 1], m.n[3 * i + 2]]);
    // unity -> scene mirror
    pos[3 * i] = v[0]; pos[3 * i + 1] = v[1]; pos[3 * i + 2] = -v[2];
    nrm[3 * i] = n[0]; nrm[3 * i + 1] = n[1]; nrm[3 * i + 2] = -n[2];
  }
  // winding check: geometric normal vs mean vertex normal
  const idx = m.i.slice();
  let agree = 0, disagree = 0;
  for (let t = 0; t < idx.length; t += 3) {
    const [a, b, c] = [idx[t], idx[t + 1], idx[t + 2]];
    const A = pos.slice(3 * a, 3 * a + 3), B = pos.slice(3 * b, 3 * b + 3), C = pos.slice(3 * c, 3 * c + 3);
    const e1 = [B[0] - A[0], B[1] - A[1], B[2] - A[2]], e2 = [C[0] - A[0], C[1] - A[1], C[2] - A[2]];
    const g = [e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0]];
    const nn = [0, 1, 2].map((k) => nrm[3 * a + k] + nrm[3 * b + k] + nrm[3 * c + k]);
    const d = g[0] * nn[0] + g[1] * nn[1] + g[2] * nn[2];
    if (d >= 0) agree++; else disagree++;
  }
  const flip = disagree > agree;
  if (flip) for (let t = 0; t < idx.length; t += 3) { const tmp = idx[t + 1]; idx[t + 1] = idx[t + 2]; idx[t + 2] = tmp; }
  const r4 = (x) => Math.round(x * 1e4) / 1e4, r3 = (x) => Math.round(x * 1e3) / 1e3;
  const mn = [0, 1, 2].map((k) => r4(Math.min(...pos.filter((_, i) => i % 3 === k))));
  const mx = [0, 1, 2].map((k) => r4(Math.max(...pos.filter((_, i) => i % 3 === k))));
  out[name] = { p: pos.map(r4), n: nrm.map(r3), i: idx, bbox: [mn, mx] };
  const s = JSON.stringify(out[name]).length; total += s;
  console.log(name.padEnd(10), "verts", nv, "tris", idx.length / 3, "flip", flip, `(${agree}/${disagree})`, "bbox", JSON.stringify(mn), JSON.stringify(mx), "bytes", s);
}
out._meta = { source: "ScoreSaber/watch @6926860 (GPL-3.0), Assets/Models — Unity prefab transforms baked, scene-local: Unity import negates x, scene mirrors z",
  parts: Object.fromEntries(Object.entries(parts).map(([k, v]) => [k, v.src])) };
writeFileSync("models.json", JSON.stringify(out));
// ES module form for the viewer (plain object literal: no JSON import
// attributes needed in Node or Vite)
const banner = `// GENERATED by scratchpad/models/compose.mjs — do not edit by hand.
// ScoreSaber watch (github.com/ScoreSaber/watch @6926860, an ArcViewer
// fork, GPL-3.0) Assets/Models, converted with Blender 5.0.1 and composed
// with the Unity import scale, the prefab child transforms and the scene
// scale baked in, in the viewer's SCENE-LOCAL frame (Unity x negated on
// import, scene z mirrored). Units: meters. p = positions, n = normals,
// i = triangle indices, bbox = [min, max]. See research/vendor/
// scoresaber-watch/SOURCE.md ("Models") for the transform ledger.
`;
writeFileSync("models.data.js", banner + "export default " + JSON.stringify(out) + ";\n");
console.log("total bytes", total);
