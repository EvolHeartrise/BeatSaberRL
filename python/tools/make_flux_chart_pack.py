"""The WebXR Flux game's bundled chart pack (SPEC.md §Flux WebXR game).

Every chart comes from the training generator (flux_chart.py, generator
f1) — the "training" entries at its DEFAULT config, i.e. exactly the
distribution the agent trains on — and is written at full float
precision, so the game plays the object stream the env would build for
that seed. Output: viz/app/src/lib/fluxcharts.data.js (committed;
python/tests/test_flux_game_parity.py fails when it is stale).

Run: python tools/make_flux_chart_pack.py [OUT] [--check]
"""
from __future__ import annotations

import argparse
import dataclasses
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from beat_arena_env.flux_chart import FluxConfig, generate_flux_chart  # noqa: E402

DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "..", "..", "viz", "app", "src", "lib",
                           "fluxcharts.data.js")

# (id, name, blurb, FluxConfig overrides, seed)
PACK = (
    ("warmup-1", "Warm-up I", "slow (7–9 m/s), sparse, 30 s",
     dict(chart_len_s=30.0, note_speed_min=7.0, note_speed_max=9.0,
          circle_prob=0.18, bar_prob=0.08), 101),
    ("warmup-2", "Warm-up II", "slow (7–9 m/s), sparse, 30 s",
     dict(chart_len_s=30.0, note_speed_min=7.0, note_speed_max=9.0,
          circle_prob=0.18, bar_prob=0.08), 102),
    ("train-1", "Training A", "the agent's training distribution, 20 s",
     {}, 1),
    ("train-2", "Training B", "the agent's training distribution, 20 s",
     {}, 2),
    ("train-3", "Training C", "the agent's training distribution, 20 s",
     {}, 3),
    ("train-4", "Training D", "the agent's training distribution, 20 s",
     {}, 4),
    ("long-1", "Marathon", "training density and speed, 60 s",
     dict(chart_len_s=60.0), 201),
    ("bars-1", "Bar Storm", "bars only, training speed, 30 s",
     dict(chart_len_s=30.0, circle_prob=0.0, bar_prob=0.35), 301),
)


def build():
    out = []
    for cid, name, blurb, over, seed in PACK:
        cfg = FluxConfig(**over)
        chart = generate_flux_chart(cfg, np.random.default_rng(seed))
        cfg_d = {k: (list(v) if isinstance(v, tuple) else v)
                 for k, v in dataclasses.asdict(cfg).items()}
        out.append({
            "id": cid, "name": name, "blurb": blurb, "seed": seed,
            "config": cfg_d,
            "chart": [{"t": o.hit_time, "x": o.x, "y": o.y, "kind": o.kind,
                       "color": o.color, "rot": o.rot, "speed": o.speed,
                       "len": o.length, "sweet": o.sweet} for o in chart],
        })
    return out


def render(pack):
    return ("// GENERATED by python/tools/make_flux_chart_pack.py — do not "
            "edit.\n// Flux generator f1 charts (flux_chart.py) for the WebXR "
            "game; see SPEC.md §Flux WebXR game.\n"
            "export default " + json.dumps(pack, separators=(",", ":")) + ";\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out", nargs="?", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(build())
    if args.check:
        with open(args.out) as f:
            if f.read() != text:
                sys.exit(f"{args.out} is stale: regenerate with "
                         "python tools/make_flux_chart_pack.py")
        return
    with open(args.out, "w") as f:
        f.write(text)
    print(f"{args.out}: {len(PACK)} charts", file=sys.stderr)


if __name__ == "__main__":
    main()
